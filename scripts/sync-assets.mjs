// Rebuild self-hosted Google Fonts and authentic company SVGs from locked npm packages.
import {mkdirSync, copyFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {createRequire} from 'node:module';
import * as icons from 'simple-icons';
const require = createRequire(import.meta.url);
const root = process.cwd();
const copy = (from, to) => {mkdirSync(dirname(to), {recursive: true}); copyFileSync(from, to);};
for (const weight of [400, 500, 600, 700]) {
  for (const subset of ['arabic', 'latin']) {
    const name = `ibm-plex-sans-arabic-${subset}-${weight}-normal.woff2`;
    copy(require.resolve(`@fontsource/ibm-plex-sans-arabic/files/${name}`), join(root, 'public/fonts/ibm-plex-sans-arabic', name));
  }
}
for (const name of ['space-grotesk', 'jetbrains-mono']) {
  const file = `${name}-latin-wght-normal.woff2`;
  copy(require.resolve(`@fontsource-variable/${name}/files/${file}`), join(root, 'public/fonts', name, file));
}
for (const [pkg, name] of [['@fontsource/ibm-plex-sans-arabic', 'IBM-Plex-Sans-Arabic'], ['@fontsource-variable/space-grotesk', 'Space-Grotesk'], ['@fontsource-variable/jetbrains-mono', 'JetBrains-Mono']]) {
  copy(join(dirname(require.resolve(`${pkg}/package.json`)), 'LICENSE'), join(root, `assets/licenses/${name}-OFL.txt`));
}
const names = ['siReact', 'siTypescript', 'siGithub', 'siPython', 'siNodedotjs', 'siFigma', 'siGooglefonts', 'siVite', 'siClaude', 'siGooglegemini', 'siX'];
const paths = {};
const manifest = [];
for (const name of names) {
  const icon = icons[name];
  if (!icon) throw new Error(`Missing icon: ${name}`);
  paths[icon.slug] = icon.path;
  manifest.push({title: icon.title, slug: icon.slug, hex: icon.hex, source: icon.source});
  writeFileSync(join(root, `public/icons/${icon.slug}.svg`), icon.svg.replace('<path ', '<path fill="currentColor" '));
}
mkdirSync(join(root, 'src/remotion/lib'), {recursive: true});
writeFileSync(join(root, 'src/remotion/lib/brand-icons.ts'), `// Generated by scripts/sync-assets.mjs from simple-icons (CC0 package; trademarks belong to owners).\nexport const brandPaths: Record<string, string> = ${JSON.stringify(paths, null, 2)};\n`);
writeFileSync(join(root, 'public/icons/manifest.json'), JSON.stringify(manifest, null, 2));
copy(join(root, 'node_modules/simple-icons/LICENSE.md'), join(root, 'assets/licenses/Simple-Icons-CC0.txt'));
console.log(`Synced 3 Google Font families and ${names.length} SVG company icons.`);
